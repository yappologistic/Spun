    void cassetteCarrierHasOpeningsAndClosedEdges() {
        CassettePlateGeometry mesh;
        const auto data=mesh.vertexData();QVERIFY(!data.isEmpty());QVERIFY(data.size()<60000);
        const auto *v=reinterpret_cast<const float*>(data.constData());
        std::map<std::array<float,6>,int> edges;
        for(int i=0;i<data.size()/int(sizeof(float));i+=24) {
            std::array<std::array<float,3>,3> points;
            for(int k=0;k<3;++k) {
                const int n=i+k*8;
                for(int j=0;j<8;++j)QVERIFY(std::isfinite(v[n+j]));
                QVERIFY(std::abs(QVector3D(v[n+3],v[n+4],v[n+5]).length()-1)<.001);
                points[k]={v[n],v[n+1],v[n+2]};
            }
            for(int k=0;k<3;++k) {
                auto a=points[k],b=points[(k+1)%3];if(b<a)std::swap(a,b);
                ++edges[{a[0],a[1],a[2],b[0],b[1],b[2]}];
            }
            const float cx=(v[i]+v[i+8]+v[i+16])/3,cy=(v[i+1]+v[i+9]+v[i+17])/3;
            if(std::abs(v[i+5])>.99) {
                QVERIFY(!(cx>-109&&cx<-76&&cy>-7&&cy<36));
                QVERIFY(!(cx>35&&cx<60&&cy>-31&&cy<36));
            }
        }
        for(const auto &[edge,count]:edges){Q_UNUSED(edge);QCOMPARE(count,2);}
        QCOMPARE(mesh.boundsMax().z()-mesh.boundsMin().z(),3.f);
    }
