    void qmlInitializationRetainsFinalPropertiesAndLiveUpdates() {
        // Batching initial QML assignments must produce the same data as the
        // C++ setters, and must not suppress changes after componentComplete.
        const auto verify=[&]<typename T>(const char *name,const QByteArray &declaration,
                                         const QVariantMap &initial,const char *property,const QVariant &next) {
            qmlRegisterType<T>("GeometryLifecycle",1,0,name);
            QQmlEngine engine;
            QQmlComponent component(&engine);
            component.setData("import QtQuick\nimport GeometryLifecycle 1.0\n"+QByteArray(name)+" { "+declaration+" }",QUrl());
            QTRY_VERIFY_WITH_TIMEOUT(component.status()!=QQmlComponent::Loading,3000);
            QVERIFY2(component.isReady(),qPrintable(component.errorString()));
            std::unique_ptr<QObject> object(component.create());
            auto *qml=qobject_cast<T*>(object.get());QVERIFY(qml);
            T native;
            for(auto it=initial.cbegin();it!=initial.cend();++it)QVERIFY(native.setProperty(it.key().toLatin1(),it.value()));
            const auto bytes=[](T *item) {
                if constexpr(std::is_base_of_v<QQuick3DGeometry,T>)return item->vertexData();
                else return item->textureData();
            };
            QCOMPARE(bytes(qml),bytes(&native));
            const auto before=bytes(qml);
            QVERIFY(qml->setProperty(property,next));QVERIFY(native.setProperty(property,next));
            QCOMPARE(bytes(qml),bytes(&native));QVERIFY(bytes(qml)!=before);
        };
        verify.operator()<DeckGeometry>("DeckGeometry","dimensions: Qt.vector3d(12, 21, 11); radius: 3",
            {{"dimensions",QVector3D(12,21,11)},{"radius",3.f}},"radius",2.f);
        verify.operator()<RecordGeometry>("RecordGeometry","radius: 40; hole: 4; depth: 3; grooves: true",
            {{"radius",40.f},{"hole",4.f},{"depth",3.f},{"grooves",true}},"radius",36.f);
        verify.operator()<WaveGeometry>("WaveGeometry","progress: 0.6; phase: 1.7; amplitude: 2.4; linear: true",
            {{"progress",.6f},{"phase",1.7f},{"amplitude",2.4f},{"linear",true}},"phase",2.f);
        verify.operator()<TurntableDetailGeometry>("TurntableDetailGeometry","fascia: true",{{"fascia",true}},"fascia",false);
        verify.operator()<SurfaceTexture>("SurfaceTexture","kind: \"vinyl-normal\"",{{"kind","vinyl-normal"}},"kind","bead-normal");
        verify.operator()<StudioTexture>("StudioTexture","tint: \"#80b8e8\"; ambientLift: 0.3",
            {{"tint",QColor("#80b8e8")},{"ambientLift",.3f}},"tint",QColor("#e8ac80"));
        verify.operator()<CoverTexture>("CoverTexture","paper: true; title: \"Album\"; artist: \"Artist\"",
            {{"paper",true},{"title","Album"},{"artist","Artist"}},"title","Changed album");
    }
